-- Run this in your Supabase Dashboard -> SQL Editor to set up J.A.R.V.I.S. cloud storage

create table if not exists public.jarvis_notes (
  id text primary key,
  text text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.jarvis_timers (
  id text primary key,
  label text not null default 'Focus Timer',
  duration integer not null default 300,
  started_at double precision not null,
  ends_at double precision not null,
  created_at timestamptz not null default now()
);

create table if not exists public.jarvis_messages (
  id bigint generated by default as identity primary key,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  persona text not null default 'butler',
  created_at timestamptz not null default now()
);

-- Enable Row Level Security (RLS)
alter table public.jarvis_notes enable row level security;
alter table public.jarvis_timers enable row level security;
alter table public.jarvis_messages enable row level security;

-- Open policies for single-user / demo HUD (tighten with auth.uid() if you add Supabase Auth)
drop policy if exists "Allow all on jarvis_notes" on public.jarvis_notes;
create policy "Allow all on jarvis_notes" on public.jarvis_notes for all using (true) with check (true);

drop policy if exists "Allow all on jarvis_timers" on public.jarvis_timers;
create policy "Allow all on jarvis_timers" on public.jarvis_timers for all using (true) with check (true);

drop policy if exists "Allow all on jarvis_messages" on public.jarvis_messages;
create policy "Allow all on jarvis_messages" on public.jarvis_messages for all using (true) with check (true);